#!/usr/bin/env node
/**
 * JERRYBAY — deterministic content-board generator for /insights/.
 *
 * No CMS, no backend, no framework. Reads content/posts/*.md (lightweight
 * frontmatter + optional Markdown-lite body), and writes:
 *   - insights/index.html            (category board, newest first)
 *   - insights/<slug>/index.html     (one per post that has body content)
 *
 * External-only posts (external_url, no body) do not get a detail page —
 * their card in the index links straight out.
 *
 * Run from the repo root:
 *   node scripts/content/build-content.mjs
 *
 * This file and every insights/**\/index.html it writes are GENERATED.
 * Edit content/posts/*.md and rerun this script instead of hand-editing
 * the generated HTML.
 */

import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const POSTS_DIR = join(ROOT, "content", "posts");
const INSIGHTS_DIR = join(ROOT, "insights");
const GENERATED_MARK = "<!-- GENERATED by scripts/content/build-content.mjs — do not hand-edit; edit content/posts/*.md and rerun. -->";

// Canonical taxonomy — order controls filter button order. A category only
// gets a filter button in the rendered board when it has >=1 post, so an
// unpopulated category never produces a dead filter.
const CATEGORIES = ["AI 활용", "업무 자동화", "노코드 제작", "사업·기획", "강의·자료", "빌드 노트"];

const NAV = [
  ["/resume/", "소개·이력"],
  ["/work/", "프로젝트"],
  ["/lab/", "직접 만든 것"],
  ["/insights/", "콘텐츠"],
  ["/books/", "전자책"],
  ["/contact/", "문의"],
];

function escapeHtml(s) {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/** Very small Markdown-lite: paragraphs, **bold**, [text](url). No HTML passthrough. */
function renderBody(raw) {
  const paragraphs = raw
    .trim()
    .split(/\n\s*\n/)
    .map((p) => p.trim())
    .filter(Boolean);
  return paragraphs
    .map((p) => {
      let escaped = escapeHtml(p);
      escaped = escaped.replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
      escaped = escaped.replace(/\[([^\]]+)\]\(([^)]+)\)/g, (_, text, url) => {
        const external = /^https?:\/\//.test(url);
        return external
          ? `<a href="${url}" target="_blank" rel="noopener noreferrer">${text}</a>`
          : `<a href="${url}">${text}</a>`;
      });
      return `        <p>${escaped}</p>`;
    })
    .join("\n");
}

/** Hand-rolled frontmatter parser: `---\nkey: "value"\n---\nbody`. No YAML dependency. */
function parsePost(fileText, filename) {
  const match = fileText.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) throw new Error(`${filename}: missing frontmatter block`);
  const [, fm, body] = match;
  const data = {};
  for (const line of fm.split(/\r?\n/)) {
    if (!line.trim()) continue;
    const m = line.match(/^([a-zA-Z_]+):\s*(.*)$/);
    if (!m) continue;
    let [, key, value] = m;
    value = value.trim();
    if (/^".*"$/.test(value)) value = value.slice(1, -1);
    else if (value === "true") value = true;
    else if (value === "false") value = false;
    data[key] = value;
  }
  const required = ["title", "date", "category", "summary"];
  const missing = required.filter((k) => !data[k]);
  if (missing.length) throw new Error(`${filename}: missing frontmatter field(s): ${missing.join(", ")}`);
  if (!CATEGORIES.includes(data.category)) {
    throw new Error(`${filename}: category "${data.category}" is not in the canonical taxonomy (${CATEGORIES.join(", ")})`);
  }
  data.slug = data.slug || filename.replace(/\.md$/, "");
  data.body = body.trim();
  data.hasDetail = data.body.length > 0;
  if (!data.hasDetail && !data.external_url) {
    throw new Error(`${filename}: post has neither body content nor external_url — nothing to link to`);
  }
  return data;
}

function loadPosts() {
  if (!existsSync(POSTS_DIR)) return [];
  return readdirSync(POSTS_DIR)
    .filter((f) => f.endsWith(".md"))
    .map((f) => parsePost(readFileSync(join(POSTS_DIR, f), "utf8"), f))
    .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));
}

function navHtml(current) {
  return NAV.map(([href, label]) =>
    href === current ? `<a href="${href}" aria-current="page">${label}</a>` : `<a href="${href}">${label}</a>`
  ).join("\n      ");
}

