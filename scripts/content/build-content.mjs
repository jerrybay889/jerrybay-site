function formatDate(d) {
  const [y, m, day] = d.split("-");
  return `${y}.${m}.${day}`;
}

function renderCard(post) {
  const href = post.hasDetail ? `/insights/${post.slug}/` : post.external_url;
  const targetAttrs = post.hasDetail ? "" : ` target="_blank" rel="noopener noreferrer"`;
  const arrow = post.hasDetail ? "" : ' <span aria-hidden="true">↗</span>';
  return `        <article class="card content-card" data-category="${escapeHtml(post.category)}">
          <div class="chip-row"><span class="chip chip--pending">${escapeHtml(post.category)}</span></div>
          <h3><a href="${href}"${targetAttrs}>${escapeHtml(post.title)}${arrow}</a></h3>
          <p>${escapeHtml(post.summary)}</p>
          <p class="dim">${formatDate(post.date)}</p>
        </article>`;
}

function buildIndex(posts) {
  const populated = CATEGORIES.filter((c) => posts.some((p) => p.category === c));
  const filterButtons = [
    `<button type="button" class="content-filter__btn is-active" data-filter="전체">전체</button>`,
    ...populated.map((c) => `<button type="button" class="content-filter__btn" data-filter="${escapeHtml(c)}">${escapeHtml(c)}</button>`),
  ].join("\n        ");

  const cards = posts.map(renderCard).join("\n\n");

  const body = `
  <section class="hero">
    <div class="wrap">
      <span class="eyebrow">콘텐츠</span>
      <h1>AI를 쓰고, 만들고, 가르치며 기록합니다.</h1>
      <p class="lead">새로운 도구 소식보다 실제 업무와 사업에 적용해본 방법을 중심으로 정리합니다.</p>
    </div>
  </section>

  <section class="section" aria-labelledby="board-h">
    <div class="wrap">
      <h2 id="board-h" class="visually-hidden">전체 콘텐츠</h2>
      <div class="content-filter" role="group" aria-label="카테고리 필터">
        ${filterButtons}
      </div>
      <div class="grid grid--3 mt-9" id="content-grid">
${cards}
      </div>
    </div>
  </section>
`;
  return pageShell({
    title: "콘텐츠 — 배제협 · JerryBay",
    description: "AI를 쓰고, 만들고, 가르치며 기록한 실무 노트, 강의, 언론 인터뷰 아카이브.",
    current: "/insights/",
    body,
  });
}

function buildDetail(post) {
  const externalLine = post.external_url
    ? `        <p><a href="${post.external_url}" target="_blank" rel="noopener noreferrer">관련 자료 보기 ↗</a></p>\n`
    : "";
  const body = `
  <section class="hero">
    <div class="wrap">
      <span class="eyebrow">${escapeHtml(post.category)}</span>
      <h1>${escapeHtml(post.title)}</h1>
      <p class="dim">${formatDate(post.date)}</p>
    </div>
  </section>

  <section class="section" aria-labelledby="post-h">
    <div class="wrap">
      <h2 id="post-h" class="visually-hidden">본문</h2>
${renderBody(post.body)}
${externalLine}      <div class="btn-row">
        <a class="btn btn--secondary" href="/insights/">← 콘텐츠 목록으로</a>
      </div>
    </div>
  </section>
`;
  return pageShell({
    title: `${post.title} — 배제협 · JerryBay`,
    description: post.summary,
    current: "/insights/",
    body,
  });
}

// --- run ---------------------------------------------------------------

const posts = loadPosts();
if (posts.length < 3) {
  console.error(`Need at least 3 seed posts in content/posts/, found ${posts.length}.`);
  process.exit(1);
}

mkdirSync(INSIGHTS_DIR, { recursive: true });
const written = [];

// Clean up stale generated detail directories before regenerating, so a
// removed/renamed post doesn't leave an orphaned page behind.
const currentSlugs = new Set(posts.filter((p) => p.hasDetail).map((p) => p.slug));
if (existsSync(INSIGHTS_DIR)) {
  for (const entry of readdirSync(INSIGHTS_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const detailFile = join(INSIGHTS_DIR, entry.name, "index.html");
    if (!currentSlugs.has(entry.name) && existsSync(detailFile)) {
      const contents = readFileSync(detailFile, "utf8");
      if (contents.includes(GENERATED_MARK)) {
        rmSync(join(INSIGHTS_DIR, entry.name), { recursive: true, force: true });
        console.log(`removed stale: insights/${entry.name}/`);
      }
    }
  }
}

const indexPath = join(INSIGHTS_DIR, "index.html");
writeFileSync(indexPath, buildIndex(posts), "utf8");
written.push("insights/index.html");

for (const post of posts) {
  if (!post.hasDetail) continue;
  const dir = join(INSIGHTS_DIR, post.slug);
  mkdirSync(dir, { recursive: true });
  const detailPath = join(dir, "index.html");
  writeFileSync(detailPath, buildDetail(post), "utf8");
  written.push(`insights/${post.slug}/index.html`);
}

console.log(`Built ${posts.length} posts (${posts.filter((p) => p.hasDetail).length} detail pages, ${posts.filter((p) => !p.hasDetail).length} external-only).`);
console.log("Files written:");
for (const f of written) console.log(`  ${f}`);
